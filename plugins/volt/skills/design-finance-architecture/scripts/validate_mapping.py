"""Offline checker for a legacy-to-target account mapping at one fixed grain.

    python3 -I scripts/validate_mapping.py FILE.json

Projects legacy signed balances through weighted mappings and compares the result, exactly, with
independently supplied target balances by entity/basis/currency/period/account. Prints a
result.schema.json-shaped report. Exit 0: every executed check passed. Exit 1: a check failed.
Exit 2: the file could not be read. See references/controls-validation.md.
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fa_common import EXACT, Report, cli, nonblank, parse_decimal  # noqa: E402

BOUNDARY = ("entity", "basis", "currency", "period")
ROW_FIELDS = BOUNDARY + ("account", "balance")

SCOPES = {
    "M_STRUCTURE": "document: tenant_id, target_accounts, legacy, mapping and target sections with required fields",
    "M_AMOUNT_FORMAT": "balances are signed fixed-point decimal strings of at most 38 digits",
    "M_UNIQUE_KEYS": "legacy rows, target rows and mapping sources are unique",
    "M_TARGET_ACCOUNTS_EXIST": "target account list is unique and every mapped or target account is in it",
    "M_WEIGHTS": "split weights are positive decimals, distinct targets, summing exactly to 1",
    "M_RETIREMENT": "retired sources carry only zero balances",
    "M_SOURCE_COVERAGE": "every legacy account has a mapping",
    "M_PRESERVATION": "projected balances equal target balances exactly per entity/basis/currency/period/account",
}
NOT_RUN = {
    "TARGET_INDEPENDENCE": "cannot prove target balances were produced independently of this mapping",
    "PRODUCT_DETAIL_DERIVATION": "missing product or instrument detail is not derived",
    "OPEN_ITEM_MIGRATION": "open items are not migrated or matched",
    "FX_BASIS_TRANSFORMATION": "currency, basis, period or presentation changes need a separate approved bridge",
    "STATEMENT_SIGN_VALIDATION": "financial-statement sign conventions are not validated",
    "EPM_INTERSECTIONS": "EPM member and dimension intersections are not checked",
    "JOURNAL_LOGIC": "journal and accounting-rule logic is not measured",
}
LIMITATIONS = [
    "Account mapping at one fixed grain only; boundaries (entity, basis, currency, period) are never transformed.",
    "Target balances must come from an independent source; a target generated by this mapping proves nothing.",
]


def validate(doc) -> dict:
    report = Report(doc, SCOPES, dict(NOT_RUN))
    if not _structure(doc, report):
        for cid in SCOPES:
            if cid != "M_STRUCTURE":
                report.skip(cid, "skipped because M_STRUCTURE failed")
        return report.render(LIMITATIONS)

    accounts = doc["target_accounts"]
    for acct, n in Counter(accounts).items():
        if n > 1:
            report.fail("M_TARGET_ACCOUNTS_EXIST", f"target account {acct} listed {n} times")
    account_set = set(accounts)

    balances = {}
    for section in ("legacy", "target"):
        counts = Counter()
        for row in doc[section]:
            key = tuple(row[f] for f in BOUNDARY) + (row["account"],)
            counts[key] += 1
            value = parse_decimal(row["balance"], signed=True)
            if value is None:
                report.fail("M_AMOUNT_FORMAT", f"{section} {'/'.join(key)} balance {row['balance']!r}")
            balances[(section, key)] = value
        for key, n in counts.items():
            if n > 1:
                report.fail("M_UNIQUE_KEYS", f"{section} row {'/'.join(key)} appears {n} times")
    for row in doc["target"]:
        if row["account"] not in account_set:
            report.fail("M_TARGET_ACCOUNTS_EXIST", f"target row account {row['account']} not in target_accounts")

    mapping = {}
    for src, n in Counter(m["source"] for m in doc["mapping"]).items():
        if n > 1:
            report.fail("M_UNIQUE_KEYS", f"mapping source {src} appears {n} times")
    for m in doc["mapping"]:
        mapping[m["source"]] = m
        if m.get("retire"):
            continue
        weights = []
        names = Counter(t["account"] for t in m["targets"])
        for acct, n in names.items():
            if n > 1:
                report.fail("M_WEIGHTS", f"source {m['source']} maps to {acct} {n} times")
        for t in m["targets"]:
            if t["account"] not in account_set:
                report.fail("M_TARGET_ACCOUNTS_EXIST", f"source {m['source']} maps to unknown account {t['account']}")
            w = parse_decimal(t["weight"], signed=False)
            if w is None or w <= 0:
                report.fail("M_WEIGHTS", f"source {m['source']} weight {t['weight']!r} for {t['account']} must be a positive decimal")
            else:
                weights.append(w)
        if len(weights) == len(m["targets"]):
            total = EXACT.create_decimal(0)
            for w in weights:
                total = EXACT.add(total, w)
            if total != 1:
                report.fail("M_WEIGHTS", f"source {m['source']} weights sum to {total}, not 1")

    for row in doc["legacy"]:
        m = mapping.get(row["account"])
        if m is None:
            report.fail("M_SOURCE_COVERAGE", f"legacy account {row['account']} has no mapping")
        elif m.get("retire"):
            value = balances[("legacy", tuple(row[f] for f in BOUNDARY) + (row["account"],))]
            if value is not None and value != 0:
                report.fail("M_RETIREMENT", f"retired account {row['account']} has balance {row['balance']} in {'/'.join(row[f] for f in BOUNDARY)}")

    blocking = {"M_AMOUNT_FORMAT", "M_WEIGHTS", "M_SOURCE_COVERAGE", "M_UNIQUE_KEYS"} & set(report.status)
    if blocking:
        report.skip("M_PRESERVATION", f"skipped because {', '.join(sorted(blocking))} failed")
    else:
        projected = defaultdict(lambda: EXACT.create_decimal(0))
        for row in doc["legacy"]:
            m = mapping[row["account"]]
            if m.get("retire"):
                continue
            value = balances[("legacy", tuple(row[f] for f in BOUNDARY) + (row["account"],))]
            for t in m["targets"]:
                key = tuple(row[f] for f in BOUNDARY) + (t["account"],)
                projected[key] = EXACT.add(projected[key], EXACT.multiply(value, parse_decimal(t["weight"], signed=False)))
        target = {key: v for (section, key), v in balances.items() if section == "target"}
        for key in sorted(set(projected) | set(target)):
            p, t = projected.get(key, 0), target.get(key, 0)
            if p != t:
                report.fail("M_PRESERVATION", f"{'/'.join(key)} projected {p} != target {t}")

    for cid in SCOPES:
        report.done(cid)
    return report.render(LIMITATIONS)


def _structure(doc, report) -> bool:
    if not isinstance(doc, dict):
        report.fail("M_STRUCTURE", "document must be a JSON object")
        return False
    ok = True
    if not nonblank(doc.get("tenant_id")):
        report.fail("M_STRUCTURE", "tenant_id is required")
        ok = False
    accounts = doc.get("target_accounts")
    if not isinstance(accounts, list) or not all(nonblank(a) for a in accounts):
        report.fail("M_STRUCTURE", "target_accounts must be a list of account strings")
        ok = False
    for section in ("legacy", "target"):
        rows = doc.get(section)
        if not isinstance(rows, list):
            report.fail("M_STRUCTURE", f"{section} must be a list")
            ok = False
            continue
        for i, row in enumerate(rows):
            if not isinstance(row, dict) or any(not nonblank(row.get(f)) for f in ROW_FIELDS if f != "balance") or "balance" not in row:
                report.fail("M_STRUCTURE", f"{section}[{i}] needs {', '.join(ROW_FIELDS)}")
                ok = False
    mapping = doc.get("mapping")
    if not isinstance(mapping, list):
        report.fail("M_STRUCTURE", "mapping must be a list")
        return False
    for i, m in enumerate(mapping):
        if not isinstance(m, dict) or not nonblank(m.get("source")):
            report.fail("M_STRUCTURE", f"mapping[{i}] needs a source")
            ok = False
            continue
        has_targets, retire = "targets" in m, m.get("retire") is True
        if has_targets == retire:
            report.fail("M_STRUCTURE", f"mapping[{i}] ({m['source']}) needs exactly one of targets or retire: true")
            ok = False
        elif has_targets and (not isinstance(m["targets"], list) or not m["targets"]
                              or not all(isinstance(t, dict) and nonblank(t.get("account")) and "weight" in t for t in m["targets"])):
            report.fail("M_STRUCTURE", f"mapping[{i}] ({m['source']}) targets need account and weight")
            ok = False
    return ok


if __name__ == "__main__":
    sys.exit(cli(validate))
