/**
 * scaffold.ts — Builder scaffolder spike (D7).
 *
 * Turns an approved spec into the minimal project skeleton the codegen agent
 * then fills in. It deliberately writes only fixed, trustworthy files —
 * package.json, spec.json, README, smoke harness — never generated source
 * code. The agent owns code; the scaffolder owns the contract between them.
 */
import type { Workspace } from "./workspace";
import type { BuildSpec } from "./spec";

const PACKAGE_JSON = {
  name: "@volt/builder-app",
  private: true,
  version: "0.1.0",
  type: "module",
  scripts: {
    check: "tsc --noEmit",
    build: "vite build",
    start: "vite preview --port $PORT",
  },
  devDependencies: {
    typescript: "^5.6.0",
    vite: "^6.0.0",
  },
};

/** Placeholder the codegen agent must replace with a real staged smoke test. */
const SMOKE_MJS = `// smoke.mjs — Builder G4 smoke harness.
// The codegen agent replaces this with a staged fetch script (html-sanity,
// assets-200, routes-200). Until then it fails closed so G4 can never
// fake-pass; the browser stages of G4 run in the Builder runner itself.
const url = process.env.APP_URL;
if (!url) {
  console.error("APP_URL is required");
  process.exit(1);
}
console.error("smoke.mjs is still the placeholder — primary flow unverified");
process.exit(1);
`;

function readmeFor(spec: BuildSpec): string {
  const stories = spec.userStories
    .map((u) => `- **${u.id}** — ${u.story}\n  - Acceptance: ${u.acceptance}`)
    .join("\n");
  const entities = spec.entities
    .map(
      (e) =>
        `- **${e.name}** (${e.provenance}) — fields: ${e.fields.map((f) => `${f.name}: ${f.type}`).join(", ")}`,
    )
    .join("\n");
  const screens = spec.screens
    .map(
      (s) =>
        `- **${s.name}** — ${s.purpose}. Primary action: ${s.primaryAction}.`,
    )
    .join("\n");
  const unknowns = spec.unknowns.length
    ? spec.unknowns
        .map((u) => `- ${u.decision} — provide: ${u.resolvingInput}`)
        .join("\n")
    : "None.";

  return `# ${spec.appName}

Generated by VOLT Builder from the approved spec in \`spec.json\`.

## User stories
${stories}

## Entities
${entities}

## Screens
${screens}

## Primary flow
${spec.primaryFlow}

## Auth model
${spec.authModel}

## Open unknowns
${unknowns}
`;
}

export interface ScaffoldResult {
  files: string[];
}

/** Write the fixed skeleton into the workspace. Idempotent by design. */
export async function scaffold(ws: Workspace, spec: BuildSpec): Promise<ScaffoldResult> {
  await ws.ensure();
  await ws.write("package.json", JSON.stringify(PACKAGE_JSON, null, 2) + "\n");
  await ws.write("spec.json", JSON.stringify(spec, null, 2) + "\n");
  await ws.write("README.md", readmeFor(spec));
  await ws.write("smoke.mjs", SMOKE_MJS);
  return { files: await ws.list() };
}
