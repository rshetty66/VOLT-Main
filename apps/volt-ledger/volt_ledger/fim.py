"""Finance information model: instrument-level data, GL lineage and adjustments (CFO brain plan, section 4).

The model is held in the FSDF-derived shape (`fsdf/schema.sql`): contracts and positions, events and journals, GL
balances at full segment grain, and the map rules that say which GL account each balance type of a product posts to.
It lives in its own SQLite database next to the ledger (reference data, loaded once), while the decisions people make
about it, the adjustments, live in the append-only ledger store with evidence and review.

Lineage rule, for any GL balance (account plus optional Entity, BusinessLine, Product and CreditStage filters):

    adjusted GL = GL balance + every adjustment line on it
    traced      = instrument balances (through the map rules) + instrument-level adjustment lines
    GL level    = GL-level adjustment lines
    untraced    = adjusted GL - traced - GL level

For an instrument-backed account `untraced` must be zero to the cent ("ties"); anything else is a break. Accounts
with no map rule are traced through their journals to events and contracts as far as the journals go, and the rest is
reported as untraced, never hidden. CostCentre and Intercompany are summed over, because positions do not carry them.

Every amount is whole minor units (cents). FSDF amounts are read as text so nothing passes through floating point.
"""
from __future__ import annotations

import hashlib
import re
import sqlite3
from decimal import Decimal
from pathlib import Path

from .evidence import write_evidence
from .mapping import _next, _review
from .store import Store

APP = Path(__file__).resolve().parent.parent
SYNTHETIC = APP / "fsdf" / "synthetic_data.sql"
SCHEMA_SQL = APP / "fsdf" / "schema.sql"

SEGMENTS = ("entity", "cost_centre", "business_line", "product", "credit_stage", "intercompany")
FILTERS = ("entity", "business_line", "product", "credit_stage")
STAGES = ("1", "2", "3", "POCI", "NA")
REASONS = ("ecl_overlay", "valuation", "accrual", "reclass", "correction", "top_side", "other")
POSITION_TYPES = {"CARRYING": "n_carrying_amt", "ALLOWANCE": "n_impairment_allow", "FV_POSITIVE": "n_fair_value",
                  "FV_NEGATIVE": "n_fair_value"}


class FimError(ValueError):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(f"{code}: {message}")
        self.code = code


# ---- loading ------------------------------------------------------------------------------------------------------

def to_sqlite(sql: str, exact: bool = False) -> str:
    """Rewrite the Oracle DDL and data script for SQLite. With exact=True, decimal columns become TEXT so amounts
    keep the digits they were written with; otherwise NUMERIC, so SQL arithmetic works (the post-load checks)."""
    sql = re.sub(r"DECLARE.*?\n/\n", "", sql, flags=re.S)                     # staging generator (PL/SQL)
    sql = re.sub(r"\)\s*PARTITION BY RANGE.*?\);", ");", sql, flags=re.S)     # interval partitioning
    sql = re.sub(r"^ALTER TABLE .*?IDENTITY.*?;$", "", sql, flags=re.M)        # identity restart
    sql = re.sub(r"^COMMIT;$", "", sql, flags=re.M)
    sql = sql.replace("GENERATED BY DEFAULT AS IDENTITY", "")
    sql = re.sub(r"DATE '(\d{4}-\d{2}-\d{2})'", r"'\1'", sql)
    if exact:
        sql = re.sub(r"\bNUMBER\(\d+,[1-9]\d*\)", "TEXT", sql)
    sql = re.sub(r"\bNUMBER\(\d+(,\d+)?\)", "NUMERIC", sql)
    sql = re.sub(r"\b(VARCHAR2|CHAR)\(\d+\)", "TEXT", sql)
    sql = re.sub(r"(\w+\s+)DATE\b", r"\1TEXT", sql)
    return sql


def _fim(store: Store) -> sqlite3.Connection:
    con = getattr(store, "_fim", None)
    if con is None:
        path = ":memory:" if store.path == ":memory:" else f"{store.path}.fim"
        con = sqlite3.connect(path, check_same_thread=False)
        con.row_factory = sqlite3.Row
        store._fim = con
    return con


def dataset(store: Store) -> dict | None:
    r = store.conn.execute("SELECT * FROM fim_dataset ORDER BY dataset_id LIMIT 1").fetchone()
    if r is None:
        return None
    if not _fim(store).execute("SELECT 1 FROM sqlite_master WHERE name = 'fct_gl_balance'").fetchone():
        # The reference database was lost (for example a fresh disk): reload it from the recorded source.
        if hashlib.sha256(SYNTHETIC.read_bytes()).hexdigest() != r["sha256"]:
            raise FimError("dataset_missing", "the information model database is missing; load it again")
        _load_sql(store, SYNTHETIC.read_text())
    return dict(r)


def _load_sql(store: Store, data_sql: str) -> None:
    schema = SCHEMA_SQL.read_text()
    con = _fim(store)
    con.executescript(to_sqlite(schema[:schema.index("-- 9. POST-LOAD CHECKS")], exact=True))
    con.executescript(to_sqlite(data_sql, exact=True))


def load_information_model(store: Store, name: str = "synthetic", actor: str = "model") -> dict:
    """Load the FSDF-shaped dataset into the ledger's information model. v1 loads the bundled synthetic bank and
    insurer; loading the same data twice does nothing, and a second, different dataset is refused."""
    if name != "synthetic":
        raise FimError("unknown_dataset", "v1 loads the bundled synthetic dataset only ('synthetic')")
    data_sql = SYNTHETIC.read_text()
    sha = hashlib.sha256(data_sql.encode()).hexdigest()
    have = dataset(store)
    if have:
        if have["sha256"] != sha:
            raise FimError("dataset_exists", f"{have['dataset_id']} is already loaded; one dataset per ledger in v1")
        return {**have, "created": False, **_summary(store)}
    _load_sql(store, data_sql)
    as_of = _fim(store).execute("SELECT MAX(fic_mis_date) FROM fct_gl_balance").fetchone()[0]
    with store.transaction() as cur:
        dsid = _next(cur, "fim_dataset", "FIM")
        ev = write_evidence(cur, "load_information_model", {"name": name}, {"dataset_id": dsid, "sha256": sha},
                            [{"file": "fsdf/synthetic_data.sql", "sha256": sha}], actor)
        cur.execute("INSERT INTO fim_dataset VALUES (?,?,?,?,?,?)", (dsid, name, sha, as_of, actor, ev.evidence_id))
    return {**dataset(store), "created": True, **_summary(store)}


def _summary(store: Store) -> dict:
    con = _fim(store)
    n = lambda t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]  # noqa: E731
    return {"contracts": n("fsi_d_contract"), "positions": n("fct_position"), "journals": n("fct_journal"),
            "gl_balances": n("fct_gl_balance"), "map_rules": n("dim_gl_map_rule")}


def _require(store: Store) -> sqlite3.Connection:
    if dataset(store) is None:
        raise FimError("no_dataset", "load the information model first (load_information_model)")
    return _fim(store)


def cents(text: object) -> int:
    if text is None or text == "":
        return 0
    v = Decimal(str(text)) * 100
    if v != v.to_integral_value():
        raise FimError("precision", f"{text} has more than two decimals")
    return int(v)


# ---- shared queries -----------------------------------------------------------------------------------------------

_SEG_SQL = """
  e.v_segment_code AS entity, cc.v_segment_code AS cost_centre, bl.v_segment_code AS business_line,
  pr.v_segment_code AS product, {stage} AS credit_stage, ic.v_segment_code AS intercompany"""
_SEG_JOIN = """
  JOIN dim_org_unit e ON e.n_org_sk = {t}.n_org_sk JOIN dim_org_unit cc ON cc.n_org_sk = {t}.n_cost_centre_sk
  JOIN dim_org_unit bl ON bl.n_org_sk = {t}.n_mgmt_org_sk JOIN dim_product pr ON pr.n_product_sk = {t}.n_product_sk
  JOIN dim_org_unit ic ON ic.n_org_sk = {t}.n_ic_org_sk"""


def _match(row, filters: dict) -> bool:
    return all(row[k] == v for k, v in filters.items())


def _accounts(con) -> dict[str, dict]:
    rows = con.execute("SELECT a.*, (SELECT COUNT(*) FROM dim_gl_account c WHERE c.n_parent_gl_sk = a.n_gl_account_sk)"
                       " AS children FROM dim_gl_account a").fetchall()
    return {r["v_gl_account_code"]: dict(r) for r in rows}


def _rules(con, ledger: str) -> list[dict]:
    return [dict(r) for r in con.execute(
        "SELECT p.v_product_code, p.v_segment_code AS product, r.v_balance_type, a.v_gl_account_code AS account, r.n_sign "
        "FROM dim_gl_map_rule r JOIN dim_product p ON p.n_product_sk = r.n_product_sk "
        "JOIN dim_gl_account a ON a.n_gl_account_sk = r.n_gl_account_sk WHERE r.v_ledger = ?", (ledger,))]


def map_rules(store: Store, ledger: str = "IFRS") -> list[dict]:
    return _rules(_require(store), ledger)


def _stage(p) -> str:
    if p["f_poci"] == "Y":
        return "POCI"
    return {"1": "1", "2": "2", "3": "3"}.get(str(p["n_ifrs9_stage"] or ""), "NA")


def _positions(con, ledger: str) -> list[dict]:
    """Latest position per contract with its segments."""
    return [dict(r) for r in con.execute(
        "SELECT c.v_contract_id, c.v_contract_family, pr.v_product_code, p.*, e.v_segment_code AS entity, "
        "bl.v_segment_code AS business_line, pr.v_segment_code AS product "
        "FROM fct_position p JOIN fsi_d_contract c ON c.n_contract_sk = p.n_contract_sk "
        "JOIN dim_org_unit e ON e.n_org_sk = c.n_org_sk "
        "JOIN dim_org_unit bl ON bl.n_org_sk = COALESCE(c.n_mgmt_org_sk, -1) "
        "JOIN dim_product pr ON pr.n_product_sk = c.n_product_sk "
        "WHERE p.v_ledger = ? AND p.fic_mis_date = (SELECT MAX(fic_mis_date) FROM fct_position x "
        "WHERE x.n_contract_sk = p.n_contract_sk AND x.v_ledger = p.v_ledger)", (ledger,))]


def _position_amount(p: dict, balance_type: str) -> int:
    v = cents(p[POSITION_TYPES[balance_type]])
    if balance_type == "FV_POSITIVE":
        return max(v, 0)
    if balance_type == "FV_NEGATIVE":
        return min(v, 0)
    return v


# ---- lineage ------------------------------------------------------------------------------------------------------

def trace_gl_balance(store: Store, account: str, filters: dict | None = None, ledger: str = "IFRS",
                     top: int = 20) -> dict:
    """Trace one GL balance down to the instruments, journals and adjustments behind it."""
    con = _require(store)
    filters = {k: v for k, v in (filters or {}).items() if v not in (None, "")}
    bad = sorted(set(filters) - set(FILTERS))
    if bad:
        raise FimError("bad_filter", f"filters are {', '.join(FILTERS)}; positions do not carry {', '.join(bad)}")
    accts = _accounts(con)
    if account not in accts:
        raise FimError("unknown_account", f"{account} is not in the information model's chart")
    if accts[account]["children"]:
        raise FimError("not_posting", f"{account} is a roll-up account; trace a posting account")

    gl = sum(cents(r["n_balance"]) for r in con.execute(
        "SELECT g.n_balance, " + _SEG_SQL.format(stage="g.v_credit_stage") + " FROM fct_gl_balance g "
        "JOIN dim_gl_account a ON a.n_gl_account_sk = g.n_gl_account_sk" + _SEG_JOIN.format(t="g")
        + " WHERE a.v_gl_account_code = ? AND g.v_ledger = ?", (account, ledger)) if _match(r, filters))

    rules = [r for r in _rules(con, ledger) if r["account"] == account]
    backing = ("ifrs17_group" if any(r["v_balance_type"] == "IFRS17_LRC_LIC" for r in rules)
               else "instrument" if rules else None)
    contributions: dict[str, dict] = {}
    if backing == "instrument":
        by_product = {}
        for r in rules:
            by_product.setdefault(r["v_product_code"], []).append(r)
        for p in _positions(con, ledger):
            seg = {"entity": p["entity"], "business_line": p["business_line"], "product": p["product"],
                   "credit_stage": _stage(p)}
            if not _match(seg, filters):
                continue
            for r in by_product.get(p["v_product_code"], []):
                amt = _position_amount(p, r["v_balance_type"]) * r["n_sign"]
                if amt:
                    c = contributions.setdefault(p["v_contract_id"], {
                        "instrument_id": p["v_contract_id"], "product": p["v_product_code"], **seg, "amount_minor": 0,
                        "via": []})
                    c["amount_minor"] += amt
                    c["via"].append(f"position {r['v_balance_type']} x {r['n_sign']}")
    elif backing == "ifrs17_group":
        if set(filters) - {"entity", "product"}:
            raise FimError("bad_filter", "IFRS 17 groups carry Entity and Product only; drop the other filters")
        signs = {r["product"]: r["n_sign"] for r in rules}
        for r in con.execute(
                "SELECT g.v_group_id, g.v_measurement_model, pr.v_product_code, pr.v_segment_code AS product, "
                "e.v_segment_code AS entity, m.n_lrc, m.n_lic FROM fct_ifrs17_measurement m "
                "JOIN fsi_d_ins_group g ON g.n_group_sk = m.n_group_sk JOIN dim_product pr ON pr.n_product_sk = g.n_product_sk "
                "JOIN dim_org_unit e ON e.n_org_sk = g.n_org_sk WHERE m.fic_mis_date = "
                "(SELECT MAX(fic_mis_date) FROM fct_ifrs17_measurement x WHERE x.n_group_sk = m.n_group_sk)"):
            if r["product"] not in signs or not _match(r, filters):
                continue
            amt = (cents(r["n_lrc"]) + cents(r["n_lic"])) * signs[r["product"]]
            contributions[r["v_group_id"]] = {"instrument_id": r["v_group_id"], "product": r["v_product_code"],
                                              "entity": r["entity"], "amount_minor": amt,
                                              "via": [f"IFRS 17 group ({r['v_measurement_model']}) LRC + LIC"]}
    else:
        backing = "journal"
        for r in con.execute(
                "SELECT c.v_contract_id, pr.v_product_code, j.n_debit_amt, j.n_credit_amt, ev.v_event_type, "
                + _SEG_SQL.format(stage="j.v_credit_stage") + " FROM fct_journal j "
                "JOIN dim_gl_account a ON a.n_gl_account_sk = j.n_gl_account_sk "
                "JOIN fct_event ev ON ev.n_event_sk = j.n_event_sk "
                "JOIN fsi_d_contract c ON c.n_contract_sk = ev.n_contract_sk" + _SEG_JOIN.format(t="j")
                + " WHERE a.v_gl_account_code = ? AND j.v_ledger = ?", (account, ledger)):
            if not _match(r, filters):
                continue
            c = contributions.setdefault(r["v_contract_id"], {
                "instrument_id": r["v_contract_id"], "product": r["v_product_code"],
                **{k: r[k] for k in FILTERS}, "amount_minor": 0, "via": []})
            c["amount_minor"] += cents(r["n_debit_amt"]) - cents(r["n_credit_amt"])
            if f"journal {r['v_event_type']}" not in c["via"]:
                c["via"].append(f"journal {r['v_event_type']}")
        if not contributions:
            backing = "gl_only"

    adjs = [a for a in _adjustment_lines(store, ledger) if a["account"] == account and _match(a, filters)]
    instrument_adj = sum(a["net_minor"] for a in adjs if a["instrument_id"])
    gl_adj = sum(a["net_minor"] for a in adjs if not a["instrument_id"])
    from_instruments = sum(c["amount_minor"] for c in contributions.values())
    adjusted = gl + instrument_adj + gl_adj
    traced = from_instruments + instrument_adj
    untraced = adjusted - traced - gl_adj
    if backing in ("instrument", "ifrs17_group"):
        status = "ties" if untraced == 0 else "break"
    else:
        status = "gl_only" if backing == "gl_only" else "ties" if untraced == 0 else "partly_traced"
    ranked = sorted(contributions.values(), key=lambda c: (-abs(c["amount_minor"]), c["instrument_id"]))
    return {"account": account, "account_name": accts[account]["v_gl_account_name"],
            "concept_id": accts[account]["v_concept_id"], "ledger": ledger, "filters": filters, "backing": backing,
            "status": status, "gl_minor": gl, "from_instruments_minor": from_instruments,
            "instrument_adjustments_minor": instrument_adj, "gl_adjustments_minor": gl_adj,
            "adjusted_gl_minor": adjusted, "untraced_minor": untraced, "instrument_count": len(contributions),
            "instruments": ranked[:top], "adjustments": adjs,
            "note": {"instrument": "Positions routed through the map rules must equal the GL to the cent.",
                     "journal": "Traced through journals to events and contracts; the rest has no journal in the "
                                "model (for example opening or year-to-date balances).",
                     "gl_only": "No instrument or journal behind this balance in the model; it is owned at GL level.",
                     "ifrs17_group": "Measured per IFRS 17 group (LRC + LIC), not per policy; groups must equal the GL "
                                     "to the cent."}[backing]}


def reconcile(store: Store, ledger: str = "IFRS") -> dict:
    """Trace every instrument-backed account at Entity x BusinessLine x Product x CreditStage grain."""
    con = _require(store)
    rules = _rules(con, ledger)
    accounts = {r["account"] for r in rules if r["v_balance_type"] != "IFRS17_LRC_LIC"}
    groups = {r["account"] for r in rules if r["v_balance_type"] == "IFRS17_LRC_LIC"}
    combos = set()
    for r in con.execute(
            "SELECT a.v_gl_account_code AS account, " + _SEG_SQL.format(stage="g.v_credit_stage")
            + " FROM fct_gl_balance g JOIN dim_gl_account a ON a.n_gl_account_sk = g.n_gl_account_sk"
            + _SEG_JOIN.format(t="g") + " WHERE g.v_ledger = ?", (ledger,)):
        if r["account"] in accounts:
            combos.add((r["account"], tuple((k, r[k]) for k in FILTERS)))
        elif r["account"] in groups:
            combos.add((r["account"], (("entity", r["entity"]), ("product", r["product"]))))
    rows = []
    for account, flt in sorted(combos):
        t = trace_gl_balance(store, account, dict(flt), ledger, top=0)
        rows.append({k: t[k] for k in ("account", "filters", "status", "gl_minor", "from_instruments_minor",
                                       "instrument_adjustments_minor", "gl_adjustments_minor", "untraced_minor")})
    breaks = [r for r in rows if r["status"] != "ties"]
    return {"ledger": ledger, "balances_checked": len(rows), "ties": len(rows) - len(breaks), "breaks": breaks}


# ---- adjustments --------------------------------------------------------------------------------------------------

def _adjustment_lines(store: Store, ledger: str) -> list[dict]:
    """Every adjustment line that is not rejected, with its review state."""
    out = []
    for r in store.conn.execute(
            "SELECT l.*, a.level, a.reason_code, a.review_item_id, a.reverses_adj_id, a.period FROM adjustment_line l "
            "JOIN adjustment a ON a.adj_id = l.adj_id WHERE a.ledger = ? ORDER BY l.adj_id, l.line_no", (ledger,)):
        state = _state(store, r["review_item_id"])
        if state == "rejected":
            continue
        out.append({**{k: r[k] for k in ("adj_id", "line_no", "level", "reason_code", "period", "account",
                                          "instrument_id", *SEGMENTS)},
                    "net_minor": r["debit_minor"] - r["credit_minor"], "review": state})
    return out


def _state(store: Store, item_id: str) -> str:
    r = store.conn.execute("SELECT decision FROM review_decision WHERE item_id = ? AND stage = 'engagement_lead' "
                           "ORDER BY seq DESC LIMIT 1", (item_id,)).fetchone()
    return {"approve": "approved", "reject": "rejected", "amend": "amend_requested"}.get(r[0], "awaiting_review") \
        if r else "awaiting_review"


def _segment_values(con) -> dict[str, set[str]]:
    org = lambda h, t: {r[0] for r in con.execute(  # noqa: E731
        "SELECT v_segment_code FROM dim_org_unit WHERE (v_hierarchy_type = ? AND v_org_type = ?) OR n_org_sk = -1",
        (h, t))}
    return {"entity": org("LEGAL", "ENTITY") - {"Unassigned"}, "cost_centre": org("MGMT", "COST_CENTRE"),
            "business_line": org("MGMT", "BUSINESS_LINE"), "intercompany": org("LEGAL", "ENTITY"),
            "product": {r[0] for r in con.execute("SELECT v_segment_code FROM dim_product")}, "credit_stage": set(STAGES)}


def propose_adjustment(store: Store, level: str, period: str, reason_code: str, rationale: str, lines: list[dict],
                       actor: str, ledger: str = "IFRS", reverses: str | None = None) -> dict:
    """Propose a balanced adjustment. Instrument level: each line names an instrument and takes its segments from
    it. GL level: lines name segments directly (defaults are the unassigned members). Always reviewed by a person."""
    con = _require(store)
    if level not in ("instrument", "gl"):
        raise FimError("bad_level", "level is 'instrument' or 'gl'")
    if reason_code not in REASONS:
        raise FimError("bad_reason", f"reason_code is one of {', '.join(REASONS)}")
    if not re.fullmatch(r"[0-9]{4}-(0[1-9]|1[0-2])", period):
        raise FimError("bad_period", "period is YYYY-MM")
    if not rationale.strip():
        raise FimError("no_rationale", "say why the adjustment is needed")
    if len(lines) < 2:
        raise FimError("too_few_lines", "an adjustment needs at least two lines")
    accts = _accounts(con)
    allowed = _segment_values(con)
    positions = {p["v_contract_id"]: p for p in _positions(con, ledger)}
    out, problems = [], []
    for i, ln in enumerate(lines, 1):
        dr, cr = int(ln.get("debit_minor") or 0), int(ln.get("credit_minor") or 0)
        if dr < 0 or cr < 0 or (dr > 0) == (cr > 0):
            problems.append(f"line {i}: fill exactly one of debit or credit with a positive amount")
        acct = str(ln.get("account", ""))
        if acct not in accts:
            problems.append(f"line {i}: account {acct} is not in the chart")
        elif accts[acct]["children"]:
            problems.append(f"line {i}: account {acct} is a roll-up account")
        seg = {"entity": "001", "cost_centre": "Unassigned", "business_line": "Unassigned", "product": "None",
               "credit_stage": "NA", "intercompany": "Unassigned"}
        given = {k: str(v) for k, v in (ln.get("segments") or {}).items()}
        unknown = sorted(set(given) - set(SEGMENTS))
        if unknown:
            problems.append(f"line {i}: unknown segments {', '.join(unknown)}")
        inst = ln.get("instrument_id")
        if level == "instrument":
            p = positions.get(str(inst)) if inst else None
            if p is None:
                problems.append(f"line {i}: instrument {inst} not found; an instrument-level line names an instrument")
            else:
                own = {"entity": p["entity"], "business_line": p["business_line"], "product": p["product"],
                       "credit_stage": _stage(p)}
                clash = [k for k in own if k in given and given[k] != own[k]]
                if clash:
                    problems.append(f"line {i}: {', '.join(clash)} differ from instrument {inst}'s own segments")
                seg.update(given)
                seg.update(own)
        else:
            if inst:
                problems.append(f"line {i}: a GL-level line names no instrument; use level 'instrument'")
            seg.update(given)
        for k, v in seg.items():
            if v not in allowed[k]:
                problems.append(f"line {i}: {k} '{v}' is not a member of that segment")
        out.append({"account": acct, **seg, "instrument_id": str(inst) if level == "instrument" and inst else None,
                    "debit_minor": dr, "credit_minor": cr})
    if not problems and sum(x["debit_minor"] for x in out) != sum(x["credit_minor"] for x in out):
        problems.append(f"unbalanced: debits {sum(x['debit_minor'] for x in out)} != credits "
                        f"{sum(x['credit_minor'] for x in out)} (minor units)")
    if problems:
        raise FimError("invalid_adjustment", "; ".join(problems))
    with store.transaction() as cur:
        adj_id = _next(cur, "adjustment", "ADJ")
        ev = write_evidence(cur, "propose_adjustment", {"level": level, "period": period, "reason_code": reason_code,
                                                         "rationale": rationale, "lines": out, "reverses": reverses},
                            {"adj_id": adj_id}, [{"dataset": dataset(store)["dataset_id"]}], actor)
        item = _review(cur, "adjustment", adj_id, f"{level}-level {reason_code}: {rationale}", ev.evidence_id)
        cur.execute("INSERT INTO adjustment VALUES (?,?,?,?,?,?,?,?,?,?)",
                    (adj_id, level, ledger, period, reason_code, rationale, reverses, actor, item, ev.evidence_id))
        for n, x in enumerate(out, 1):
            cur.execute("INSERT INTO adjustment_line VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                        (adj_id, n, x["account"], *(x[k] for k in SEGMENTS), x["instrument_id"], x["debit_minor"],
                         x["credit_minor"]))
    return {"adj_id": adj_id, "level": level, "review_item_id": item, "evidence_id": ev.evidence_id, "lines": out}


def reverse_adjustment(store: Store, adj_id: str, rationale: str, actor: str) -> dict:
    a = store.conn.execute("SELECT * FROM adjustment WHERE adj_id = ?", (adj_id,)).fetchone()
    if a is None:
        raise FimError("unknown_adjustment", f"{adj_id} not found")
    if a["reverses_adj_id"]:
        raise FimError("is_reversal", f"{adj_id} is itself a reversal")
    if store.conn.execute("SELECT 1 FROM adjustment WHERE reverses_adj_id = ?", (adj_id,)).fetchone():
        raise FimError("already_reversed", f"{adj_id} has already been reversed")
    lines = [{"account": r["account"], "instrument_id": r["instrument_id"],
              "segments": {k: r[k] for k in SEGMENTS}, "debit_minor": r["credit_minor"], "credit_minor": r["debit_minor"]}
             for r in store.conn.execute("SELECT * FROM adjustment_line WHERE adj_id = ? ORDER BY line_no", (adj_id,))]
    if a["level"] == "instrument":
        for ln in lines:   # segments come from the instrument again
            ln["segments"] = {k: v for k, v in ln["segments"].items() if k in ("cost_centre", "intercompany")}
    return propose_adjustment(store, a["level"], a["period"], a["reason_code"], f"reversal of {adj_id}: {rationale}",
                              lines, actor, a["ledger"], reverses=adj_id)


def list_adjustments(store: Store) -> list[dict]:
    return [{**dict(r), "review": _state(store, r["review_item_id"])}
            for r in store.conn.execute("SELECT * FROM adjustment ORDER BY adj_id")]


def instrument_summary(store: Store, instrument_id: str, ledger: str = "IFRS") -> dict:
    """One instrument: its segments, latest position, the GL accounts it feeds and its journals."""
    con = _require(store)
    p = next((x for x in _positions(con, ledger) if x["v_contract_id"] == instrument_id), None)
    if p is None:
        raise FimError("unknown_instrument", f"{instrument_id} not found")
    feeds = []
    for r in _rules(con, ledger):
        if r["v_product_code"] == p["v_product_code"] and r["v_balance_type"] in POSITION_TYPES:
            amt = _position_amount(p, r["v_balance_type"]) * r["n_sign"]
            if amt:
                feeds.append({"account": r["account"], "balance_type": r["v_balance_type"], "amount_minor": amt})
    journals = [{"event_type": r[0], "account": r[1], "net_minor": cents(r[2]) - cents(r[3]), "date": r[4]}
                for r in con.execute(
        "SELECT ev.v_event_type, a.v_gl_account_code, j.n_debit_amt, j.n_credit_amt, j.d_accounting FROM fct_journal j "
        "JOIN fct_event ev ON ev.n_event_sk = j.n_event_sk JOIN fsi_d_contract c ON c.n_contract_sk = ev.n_contract_sk "
        "JOIN dim_gl_account a ON a.n_gl_account_sk = j.n_gl_account_sk WHERE c.v_contract_id = ? AND j.v_ledger = ? "
        "ORDER BY j.n_journal_sk", (instrument_id, ledger))]
    adjs = [a for a in _adjustment_lines(store, ledger) if a["instrument_id"] == instrument_id]
    return {"instrument_id": instrument_id, "family": p["v_contract_family"], "product": p["v_product_code"],
            "segments": {"entity": p["entity"], "business_line": p["business_line"], "product": p["product"],
                         "credit_stage": _stage(p)},
            "measure_class": p["v_measure_class"], "as_of": p["fic_mis_date"],
            "position": {k: cents(p[k]) for k in ("n_principal_bal", "n_accrued_interest", "n_carrying_amt",
                                                  "n_impairment_allow", "n_fair_value")},
            "feeds_gl": feeds, "journals": journals, "adjustments": adjs}


def chart(store: Store) -> list[dict]:
    """Posting accounts of the loaded chart, for the data requirements register."""
    con = _require(store)
    return [{"account": k, "name": v["v_gl_account_name"], "concept_id": v["v_concept_id"],
             "statement": v["v_statement_class"]} for k, v in sorted(_accounts(con).items()) if not v["children"]]

