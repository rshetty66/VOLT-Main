/** Everything the exports need from a saved run, gathered once. */
import { ORCHESTRATOR_LANE } from "../../shared/events.js";
import type { Engagement, StoredRun } from "../../shared/records.js";
import { parseMarkdown, plain, type Block } from "./markdown.js";

export interface Specialist {
  name: string;
  layer: string;
  phase?: string;
  blocks: Block[];
}

export interface ToolUse<I = Record<string, any>, D = Record<string, any>> {
  by: string;
  input: I;
  data: D;
}

export interface RunContent {
  title: string;
  client: string;
  engagementTitle: string;
  date: string;
  isDemo: boolean;
  modeLabel: string;
  status: string;
  prompt: string;
  intake: [string, string][];
  body: Block[];
  specialists: Specialist[];
  valueCases: ToolUse[];
  benchmarks: ToolUse[];
}

export function runContent(run: StoredRun, engagement: Engagement | null): RunContent {
  let body = parseMarkdown(run.finalText);
  // An agent-written H1 becomes the document title.
  const first = body.find((b) => b.kind !== "rule");
  let title = run.title;
  if (first?.kind === "heading" && first.depth === 1) {
    title = plain(first.inlines);
    body = body.filter((b) => b !== first);
  }

  const phases = new Map<number, string>();
  const lanes = new Map<string, { name: string; layer: string; phase?: string; text: string }>();
  const calls = new Map<string, { lane: string; input: any }>();
  const valueCases: ToolUse[] = [];
  const benchmarks: ToolUse[] = [];
  const laneName = (lane: string) => (lane === ORCHESTRATOR_LANE ? "Rudra" : lanes.get(lane)?.name ?? lane);

  for (const e of run.events) {
    if (e.type === "phase_start") phases.set(e.index, e.name);
    if (e.type === "agent_start" && e.lane !== ORCHESTRATOR_LANE) {
      const idx = e.lane.split(":").length === 3 ? Number(e.lane.split(":")[1]) : undefined;
      lanes.set(e.lane, { name: e.name, layer: e.layer, phase: idx === undefined ? undefined : phases.get(idx), text: "" });
    }
    if (e.type === "text_delta" && e.lane !== ORCHESTRATOR_LANE) {
      const l = lanes.get(e.lane);
      if (l) l.text += e.text;
    }
    if (e.type === "tool_call") calls.set(e.callId, { lane: e.lane, input: e.input });
    if (e.type === "tool_result" && !e.isError && e.data) {
      const call = calls.get(e.callId);
      if (!call) continue;
      const use = { by: laneName(call.lane), input: call.input, data: e.data as Record<string, any> };
      if (e.name === "build_value_case") valueCases.push(use);
      if (e.name === "apqc_benchmark") benchmarks.push(use);
    }
  }

  const seen = new Set<string>();
  const uniqueBenchmarks = benchmarks.filter((b) => {
    const key = `${b.data.benchmark?.key}:${b.data.clientValue ?? ""}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  return {
    title,
    client: engagement?.clientName ?? "",
    engagementTitle: engagement?.title ?? "",
    date: new Date(run.startedAt).toLocaleDateString("en-CA", { year: "numeric", month: "long", day: "numeric" }),
    isDemo: run.mode === "demo",
    modeLabel: run.mode === "demo" ? "Demo mode: agent text is simulated" : `Generated by VOLT agents on ${run.model}`,
    status: run.status,
    prompt: run.prompt,
    intake: Object.entries(run.intake ?? {}),
    body,
    specialists: [...lanes.values()].filter((l) => l.text.trim()).map((l) => ({ name: l.name, layer: l.layer, phase: l.phase, blocks: parseMarkdown(l.text) })),
    valueCases,
    benchmarks: uniqueBenchmarks,
  };
}

/** A safe file name stem from a title and date. */
export const fileStem = (title: string, iso: string) =>
  `${title}-${iso.slice(0, 10)}`.replace(/[^A-Za-z0-9-]+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").toLowerCase();
